import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import { format } from "oxfmt";

const runtimeDir = fileURLToPath(new URL("../", import.meta.url));
// Dependencies precede their consumers in the coverage runtime.
const helpers = {
  decoratorMetadata: [],
  setClassName: [],
  decorateElement: ["decoratorMetadata", "setClassName"],
  decoratorStart: [],
  runInitializers: [],
};
const banner = "// Generated by npm/runtime/scripts/generate-decorator-helpers.mjs. Do not edit.\n";

export async function getDecoratorHelperFiles() {
  const files = new Map();
  let coverage = "(function () {\n";
  for (const [name, dependencies] of Object.entries(helpers)) {
    const source = readFileSync(join(runtimeDir, "scripts/helpers", `${name}.js`), "utf8");
    const commonjsExports = `module.exports = _${name};\nmodule.exports.__esModule = true;\nmodule.exports["default"] = module.exports;\n`;
    const commonjsImports = dependencies
      .map((dependency) => `var _${dependency} = require("./${dependency}.js");\n`)
      .join("");
    const esmImports = dependencies
      .map((dependency) => `import _${dependency} from "./${dependency}.js";\n`)
      .join("");
    files.set(
      join(runtimeDir, "src/helpers", `${name}.js`),
      banner + commonjsImports + source + commonjsExports,
    );
    files.set(
      join(runtimeDir, "src/helpers/esm", `${name}.js`),
      banner + esmImports + source + `export { _${name} as default };\n`,
    );
    // Each helper keeps its own CommonJS scope and export properties, as in npm.
    const parameters = ["module", ...dependencies.map((dependency) => `_${dependency}`)];
    const argumentsList = [
      "{ exports: {} }",
      ...dependencies.map((dependency) => `babelHelpers.${dependency}`),
    ];
    coverage += `babelHelpers.${name} = (function (${parameters.join(", ")}) {\n${source}${commonjsExports}return module.exports;\n})(${argumentsList.join(", ")});\n`;
  }
  coverage += "})();\n";
  const coveragePath = join(runtimeDir, "../../tasks/coverage/src/runtime/decoratorHelpers.js");
  const formatted = await format(coveragePath, banner + coverage, {
    experimentalOperatorPosition: "start",
  });
  if (formatted.errors.length) throw new Error(JSON.stringify(formatted.errors));
  files.set(coveragePath, formatted.code);
  return files;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const check = process.argv.includes("--check");
  for (const [path, contents] of await getDecoratorHelperFiles()) {
    if (check) {
      if (readFileSync(path, "utf8") !== contents) {
        throw new Error(`Stale generated decorator helper: ${path}`);
      }
    } else {
      writeFileSync(path, contents);
    }
  }
}
